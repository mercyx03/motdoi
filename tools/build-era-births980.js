'use strict';

// Usage: node tools/build-era-births980.js wpp.csv.gz WPP2024_Demographic_Indicators_Medium_Update.csv
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const vm = require('node:vm');
const { createHash } = require('node:crypto');

const [mainFile, amendmentFile] = process.argv.slice(2);
if (!mainFile || !amendmentFile) throw Error('Pass both the WPP2024 medium-variant archive and the Togo amendment CSV.');
const publicJs = path.resolve(__dirname, '../public/js');
const context = {};
vm.runInNewContext(fs.readFileSync(path.join(publicJs, 'data-world.js'), 'utf8'), context);
const codes = new Set(context.G.W.C.filter(country => country.births > 0).map(country => country.code));
const FROM = 1950, ESTIMATES_TO = 2023, TO = 2025, COUNT = TO - FROM + 1;
const births = new Map(), projected = new Map();
const columns = ['ISO2_code', 'Variant', 'Time', 'Births', 'LEx', 'TFR', 'Q5'];

function read(file, gzip, onlyCountry) {
  const binary = fs.readFileSync(file);
  const source = (gzip ? zlib.gunzipSync(binary) : binary).toString('utf8').replace(/^\uFEFF/, '');
  const [header, ...records] = source.split(/\r?\n/);
  const keys = header.split(',');
  const indexes = columns.map(key => {
    const index = keys.indexOf(key);
    if (index < 0) throw Error(`Missing ${key} in ${file}`);
    return index;
  });
  const seen = new Set();
  for (const record of records) {
    if (!record) continue;
    const cells = record.match(/(?:"(?:[^"]|"")*"|[^,]*)(?:,|$)/g).map(cell => cell.replace(/,$/, '').replace(/^"|"$/g, ''));
    const [code, variant, y, b, e, t, q] = indexes.map(index => cells[index]);
    const year = Number(y);
    if (!codes.has(code) || (onlyCountry && code !== onlyCountry) || !Number.isInteger(year) || year < FROM || year > TO || variant !== 'Medium') continue;
    if (seen.has(`${code}/${year}`)) throw Error(`Duplicate row ${code}/${year} in ${file}`);
    seen.add(`${code}/${year}`);
    if (!b || !Number.isFinite(Number(b)) || Number(b) < 0) throw Error(`Invalid births ${code}/${year}`);
    if (!births.has(code)) births.set(code, Array(COUNT).fill(null));
    births.get(code)[year - FROM] = Math.round(Number(b) * 1000);
    if (year > ESTIMATES_TO) {
      if (![e, t, q].every(value => value && Number.isFinite(Number(value)) && Number(value) > 0)) throw Error(`Invalid projection ${code}/${year}`);
      if (!projected.has(code)) projected.set(code, []);
      projected.get(code)[year - ESTIMATES_TO - 1] = [Number(e), Number(t), Number(q)];
    }
  }
  if (!seen.size || (onlyCountry && seen.size !== COUNT)) throw Error(`Missing records in ${file}`);
  return createHash('sha256').update(binary).digest('hex');
}

const sha256 = { wpp: read(mainFile, true), togo: read(amendmentFile, false, 'TG') };
const series = {}, recent = {};
for (const code of codes) {
  const row = births.get(code);
  if (!row || row.includes(null) || projected.get(code)?.length !== TO - ESTIMATES_TO) throw Error(`Incomplete WPP series for ${code}`);
  series[code] = row.map((value, index) => index ? value - row[index - 1] : value).join(',');
  recent[code] = projected.get(code);
}
const data = { from: FROM, estimatesTo: ESTIMATES_TO, to: TO, sha256, births: series, recent };
const header = '/* Generated by tools/build-era-births980.js. United Nations DESA, Population Division, World Population Prospects 2024, medium variant and Togo interim update. CC BY 3.0 IGO. Birth counts in people, delta encoded. Recent: life expectancy in years, total fertility rate, under-five mortality per 1,000. */\n';
fs.writeFileSync(path.join(publicJs, 'data-era-births980.js'), header + '(function(G){\'use strict\';G.ERA_BIRTHS980=' + JSON.stringify(data) + ';})(globalThis.G=globalThis.G||{});\n');
console.log(`WPP: ${codes.size} countries, ${COUNT} years, ${projected.size} projection series.`);
